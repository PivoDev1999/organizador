// Generates src/api/schema.d.ts from the API's OpenAPI document.
// Source: http://127.0.0.1:${API_PORT}/api/openapi.json (API_PORT from the environment or the root .env,
// default 8000). If the API is not running, falls back to the saved snapshot in openapi/openapi.json.
// A successful download also refreshes the snapshot, so both files are versioned together.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("..", import.meta.url));
const snapshotPath = `${root}openapi/openapi.json`;
const outputPath = `${root}src/api/schema.d.ts`;

async function readApiPort() {
  if (process.env.API_PORT) return process.env.API_PORT;
  try {
    const env = await readFile(`${root}../.env`, "utf8");
    const match = env.match(/^\s*API_PORT\s*=\s*["']?(\d+)["']?\s*$/m);
    if (match) return match[1];
  } catch {
    // No root .env: use the default port.
  }
  return "8000";
}

async function loadSchema() {
  const url = `http://127.0.0.1:${await readApiPort()}/api/openapi.json`;
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(3000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const schema = await response.json();
    await writeFile(snapshotPath, `${JSON.stringify(schema, null, 2)}\n`);
    console.log(`OpenAPI lida de ${url} (snapshot atualizado em openapi/openapi.json).`);
    return schema;
  } catch (error) {
    console.warn(`API indisponível em ${url} (${error.message}); usando openapi/openapi.json.`);
    return JSON.parse(await readFile(snapshotPath, "utf8"));
  }
}

const ast = await openapiTS(await loadSchema());
const header = "// Generated by `npm run api:types` from the API's OpenAPI document. Do not edit.\n\n";
await writeFile(outputPath, header + astToString(ast));
console.log("Tipos gerados em src/api/schema.d.ts.");
